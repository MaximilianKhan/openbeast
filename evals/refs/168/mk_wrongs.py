#!/usr/bin/env python3
"""Derives the known-bad solutions for task 168 from the references, one
targeted edit each, so every wrong arm differs from a passing ref in exactly
the defect it is meant to exhibit:

  wrong_tie.<ext>     a response at t "precedes" an invocation at t (<= vs <)
  wrong_nopend.<ext>  unanswered operations are dropped (never take effect)
  slow_nomemo.<ext>   per-key search without memoisation (exponential)

slow_global.py / slow_global.c (unpartitioned memoised search) are written
by hand. Run: python3 mk_wrongs.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

EDITS = {
    "py": {
        "tie": [("            if calls[j] > minret:", "            if calls[j] >= minret:")],
        "nopend": [("            kind = t[2].decode()\n",
                    "            kind = t[2].decode()\n            if pending:\n                continue\n")],
        "nomemo": [("            if st not in seen:", "            if True:")],
    },
    "c": {
        "tie": [("if (ops[i].call > minret) break;", "if (ops[i].call >= minret) break;")],
        "nopend": [("if (pending && o.kind == GET) continue;", "if (pending) continue;")],
        "nomemo": [("            if (fresh) {", "            if (fresh || !fresh) {")],
    },
    "go": {
        "tie": [("if ops[i].call > minret {", "if ops[i].call >= minret {")],
        "nopend": [("if pending && o.kind == GET {", "if pending {")],
        "nomemo": [("if !seen[k] {", "if true {")],
    },
    "cpp": {
        "tie": [("if (ops[i].call > minret) break;", "if (ops[i].call >= minret) break;")],
        "nopend": [("if (pending && o.kind == GET) continue;", "if (pending) continue;")],
        "nomemo": [("if (seen.insert(nxt).second) stack.push_back(std::move(nxt));",
                    "seen.insert(nxt);\n            stack.push_back(std::move(nxt));")],
    },
    "rs": {
        "tie": [("if ops[i].call > minret {", "if ops[i].call >= minret {")],
        "nopend": [("if pending && kind == GET {", "if pending {")],
        "nomemo": [("if !seen.contains(&nxt) {", "if !seen.contains(&nxt) || true {")],
    },
    "zig": {
        "tie": [("if (ops[i].call > minret) break;", "if (ops[i].call >= minret) break;")],
        "nopend": [("if (pending and kind == .get) continue;", "if (pending) continue;")],
        "nomemo": [("            if (std.mem.eql(u64, self.state(@intCast(self.table[h])), s)) return null;\n", "")],
    },
}
NOTE = {
    "tie": "WRONG (tie): treats A.r == B.c as A-before-B; the contract says concurrent.",
    "nopend": "WRONG (pending): drops every unanswered operation, as if it never took effect.",
    "nomemo": "SLOW: per-key search with no memoisation of visited states (exponential).",
}
NAME = {"tie": "wrong_tie", "nopend": "wrong_nopend", "nomemo": "slow_nomemo"}


def main():
    for ext, edits in EDITS.items():
        ref = open(os.path.join(HERE, f"linz.{ext}")).read()
        for arm, subs in edits.items():
            s = ref
            for old, new in subs:
                assert s.count(old) == 1, (ext, arm, old)
                s = s.replace(old, new)
            lead = "# " if ext == "py" else "// "
            if ext == "py":
                s = s.replace("#!/usr/bin/env python3\n", "#!/usr/bin/env python3\n" + lead + NOTE[arm] + "\n", 1)
            else:
                s = lead + NOTE[arm] + " Generated by mk_wrongs.py.\n" + s
            open(os.path.join(HERE, f"{NAME[arm]}.{ext}"), "w").write(s)
            print("wrote", f"{NAME[arm]}.{ext}")


if __name__ == "__main__":
    main()
